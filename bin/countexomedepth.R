# load packages
library(ExomeDepth)
library(dplyr)
library(GenomicRanges)
library(Rsamtools)
library(Biostrings)
#library(readr)


args=commandArgs(trailingOnly = T) #string vector arg witch contains the entries at command lines

bed_file <- args[1]
fasta_file <- args[2]
all_bam_related_files <- args[3:length(args)]

# Filter the arguments to only select .bam files.
# The .bai files will be in the work directory but won't be processed directly.
bam_files_raw <- all_bam_related_files[grepl("\\.bam$", all_bam_related_files)]
initial_count <- length(bam_files_raw)

# Remove duplicates
bam_files <- unique(bam_files_raw)
final_count <- length(bam_files)

# Report if duplicates were found and removed
if (initial_count != final_count) {
  duplicates_removed <- initial_count - final_count
  message(paste0("\n[WARNING] Removed ", duplicates_removed, " duplicate BAM file(s)"))
  message("[WARNING] This suggests an issue in the workflow file handling")
}

message("\n[INFO] BAM files to process:")
message(paste(basename(bam_files), collapse = "\n"))
message(paste0("[INFO] Total: ", final_count, " unique BAM files\n"))

rm(args)


#bed <- as.data.frame(read_delim(bedFile, 
                                #delim = "\t", escape_double = FALSE, 
                                #col_names = FALSE, trim_ws = TRUE))

# Cargar el fichero de regiones (BED)
my_bed <- read.delim(bed_file, header = FALSE, sep = "\t", stringsAsFactors = FALSE)
my_bed <- my_bed[,1:4]
colnames(my_bed) <- c("chromosome", "start", "end", "name")

# Calculate GC content and add it as the 5th column
# 1. Create a GRanges object from the BED data
#    BED files are 0-based for start, GRanges are 1-based, so we add 1.
my_bed_granges <- GRanges(seqnames = my_bed$chromosome,
                          ranges = IRanges(start = my_bed$start + 1, end = my_bed$end))


# 2. Open the reference FASTA file
reference_fasta <- FaFile(file = fasta_file)

# 3. Get sequences for each BED region
sequences <- getSeq(reference_fasta, my_bed_granges)

# 4. Calculate GC frequency and add it to the data frame
my_bed$gc.content <- as.vector(letterFrequency(sequences, letters = "GC", as.prob = TRUE))

# Crear la matriz de cuentas
# getBamCounts will now use the 5th column 'gc.content' for correction
all.counts <- getBamCounts(bed.frame = my_bed,
                           bam.files = bam_files,
                           include.chr = FALSE)

# DEBUG: Print column names generated by getBamCounts
message("\n[DEBUG] Total columns in matrix: ", ncol(all.counts))
message("[DEBUG] All column names from getBamCounts:")
message(paste(colnames(all.counts), collapse = "\n"))

# Extract sample column names (skip first 4 metadata cols: chr, start, end, exon)
# NOTE: getBamCounts replaces 'name' with 'exon' and doesn't preserve gc.content
sample_col_names <- colnames(all.counts)[5:ncol(all.counts)]
message("\n[INFO] Sample columns (", length(sample_col_names), " total):")
message(paste(sample_col_names, collapse = "\n"))

# Verify no duplicates in sample columns
if (length(sample_col_names) != length(unique(sample_col_names))) {
  stop("[ERROR] Duplicate sample column names detected!")
}

# Prepare optimized data structures for module 2 (callexomedepth)
# Only export what's needed: dataframe and matrix, no BAM paths

# 1. ExomeCount.dafr: Complete dataframe with regions + counts
ExomeCount.dafr <- as.data.frame(all.counts)
# Note: getBamCounts already renamed 'name' to 'exon', no need to rename

# 2. ExomeCount.mat: Numeric matrix of counts only (exclude region info)
# Extract only the count columns (from column 5 onwards after: chr, start, end, exon)
count_columns <- 5:ncol(ExomeCount.dafr)
ExomeCount.mat <- as.matrix(ExomeCount.dafr[, count_columns])

message("\n[DEBUG] ExomeCount.mat dimensions: ", nrow(ExomeCount.mat), " rows x ", ncol(ExomeCount.mat), " columns")
message("[DEBUG] ExomeCount.mat column names:")
message(paste(colnames(ExomeCount.mat), collapse = "\n"))

# Save optimized data: only dataframe and matrix, no BAM paths
# This reduces file size and avoids redundancy with Nextflow BAM management
save(ExomeCount.dafr, ExomeCount.mat, file = "ExomeCount.Rdata")


